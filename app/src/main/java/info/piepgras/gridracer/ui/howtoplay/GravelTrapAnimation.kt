/**
 * Six-frame walkthrough of the gravel trap, following MoveRules: the outer wall runs along row 2,
 * the gravel lies two rows beyond it and the barrier is on row 4.
 *
 * 1. The car at (2,1) with velocity (2,1) coasts to (4,2), onto the outer wall.
 * 2. All nine candidates are legal: the wall line and row 3 are gravel.
 * 3. It runs wide to (5,3) at velocity (3,2). Unbraked it would coast to (8,5), past the barrier;
 * braked (speed 3 less 2, rounded per axis to (1,1)) it coasts to (6,4).
 * 4. Around (6,4), rows 3 and 4 are gravel and offered; row 5 lies past the barrier and is
 * withheld.
 * 5. It steers to (6,3). Moving from the gravel brakes it to a standstill coast, so the nine
 * points round the car itself are offered.
 * 6. Two crawling moves take it over the wall at (7,2) and onto the track at (8,1); that last move
 * started on the wall, so the brake holds for the two moves after it.
 *
 * Generated from tools/tutorial-editor/projects/gravel_trap.json by tools/tutorial-editor/codegen.py.
 * Edit the scene in the tutorial editor and regenerate; do not edit this file by hand.
 */

/** The phases HowToPlayScreen steps [GravelTrapAnimation] through, one per frame. */
internal val GravelTrapFrames = listOf(0f, 0.16f, 0.38f, 0.5f, 0.7f, 0.92f)

@Composable
internal fun GravelTrapAnimation(phase: Float) {
    Canvas(modifier = Modifier.fillMaxSize()) {
        val grid = drawAnimGrid(cols = 9, rows = 7)
        val cell = grid.cellSize

        val carMoves = listOf(
            AnimMove(grid.offset(2f, 1f), grid.offset(5f, 3f), 0.2f, 0.3f, Point(3, 2)),
            AnimMove(grid.offset(5f, 3f), grid.offset(6f, 3f), 0.55f, 0.62f, Point(1, 0)),
            AnimMove(grid.offset(6f, 3f), grid.offset(7f, 2f), 0.74f, 0.8f, Point(1, -1)),
            AnimMove(grid.offset(7f, 2f), grid.offset(8f, 1f), 0.82f, 0.88f, Point(1, -1)),
        )
        val car = animCar(grid.offset(2f, 1f), Point(2, 1), carMoves, phase, cell)

        // gravel
        drawAnimGravel(grid, -0.5f, 2f, 8.5f, 2f)
        // wall
        drawAnimWall(grid, -0.5f, 2f, 8.5f, 2f)
        // trail_in
        drawTrailSegment(grid.offset(0f, 0f), grid.offset(2f, 1f), cell)
        // trail_wide
        drawFollowTrail(carMoves[0], car.position, phase, cell)
        // trail_steer
        drawFollowTrail(carMoves[1], car.position, phase, cell)
        // trail_crawl
        drawFollowTrail(carMoves[2], car.position, phase, cell)
        // trail_out
        drawFollowTrail(carMoves[3], car.position, phase, cell)
        // projector_in
        drawProjector(grid.offset(2f, 1f), grid.offset(4f, 2f), cell, rampDown(phase, 0.18f, 0.25f))
        // pickers_into_gravel
        drawOfferedPickers(
            listOf(
                Point(3, 1), Point(3, 2), Point(3, 3),
                Point(4, 1), Point(4, 2), Point(4, 3),
                Point(5, 1), Point(5, 2), Point(5, 3),
            ),
            grid,
            minOf(ramp(phase, 0.08f, 0.15f), rampDown(phase, 0.18f, 0.25f)),
        )
        // ring_wide
        drawPickRing(Point(5, 3), grid, minOf(ramp(phase, 0.12f, 0.16f), rampDown(phase, 0.18f, 0.25f)))
        // projector_unbraked
        drawProjector(
            grid.offset(5f, 3f),
            grid.offset(8f, 5f),
            cell,
            minOf(ramp(phase, 0.3f, 0.32f), rampDown(phase, 0.42f, 0.48f)),
            color = AnimCrashColor,
        )
        // projector_braked
        drawProjector(
            grid.offset(5f, 3f),
            grid.offset(6f, 4f),
            cell,
            minOf(ramp(phase, 0.32f, 0.35f), rampDown(phase, 0.52f, 0.56f)),
        )
        // pickers_braked
        drawOfferedPickers(
            listOf(
                Point(5, 3), Point(6, 3), Point(7, 3),
                Point(5, 4), Point(6, 4), Point(7, 4),
            ),
            grid,
            minOf(ramp(phase, 0.42f, 0.48f), rampDown(phase, 0.52f, 0.56f)),
        )
        // pickers_past_barrier
        drawWithheldPickers(
            listOf(Point(5, 5), Point(6, 5), Point(7, 5)),
            grid,
            minOf(ramp(phase, 0.42f, 0.48f), rampDown(phase, 0.52f, 0.56f)),
        )
        // ring_steer
        drawPickRing(Point(6, 3), grid, minOf(ramp(phase, 0.49f, 0.51f), rampDown(phase, 0.52f, 0.56f)))
        // pickers_standstill
        drawOfferedPickers(
            listOf(
                Point(5, 2), Point(5, 3), Point(5, 4),
                Point(6, 2), Point(6, 3), Point(6, 4),
                Point(7, 2), Point(7, 3), Point(7, 4),
            ),
            grid,
            minOf(ramp(phase, 0.63f, 0.68f), rampDown(phase, 0.72f, 0.75f)),
        )
        // ring_crawl
        drawPickRing(Point(7, 2), grid, minOf(ramp(phase, 0.68f, 0.7f), rampDown(phase, 0.72f, 0.75f)))
        // car
        drawDemoCar(car.position, cell, car.heading, 1f)
    }
}

@Composable
internal fun gravelTrapCaption(phase: Float): String = when {
    phase < 0.16f -> stringResource(R.string.how_to_play_gravel_trap_caption_1)
    phase < 0.38f -> stringResource(R.string.how_to_play_gravel_trap_caption_2)
    phase < 0.5f -> stringResource(R.string.how_to_play_gravel_trap_caption_3)
    phase < 0.7f -> stringResource(R.string.how_to_play_gravel_trap_caption_4)
    phase < 0.92f -> stringResource(R.string.how_to_play_gravel_trap_caption_5)
    else -> stringResource(R.string.how_to_play_gravel_trap_caption_6)
}
